    // The SVGs use stroke="currentColor": substitute the tint, parse, draw.
    // Not cached on purpose - a Drawable is cheap to rebuild and caching would keep stale tints.
    inline void draw (juce::Graphics& g, Id id, juce::Rectangle<float> area, juce::Colour colour)
    {
        const auto text = juce::String (svgFor (id))
                              .replace ("currentColor", "#" + colour.withAlpha (1.0f).toDisplayString (false));

        if (auto drawable = juce::Drawable::createFromSVGString (text))
            drawable->drawWithin (g, area, juce::RectanglePlacement::centred, colour.getFloatAlpha());
    }
